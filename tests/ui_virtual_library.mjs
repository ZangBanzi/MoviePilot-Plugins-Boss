import { chromium } from '../frontend/node_modules/playwright/index.mjs'
import { readFileSync } from 'node:fs'
import assert from 'node:assert/strict'
const address = 'http://127.0.0.1:' + readFileSync('.work/preview-port.txt', 'utf8').trim()
const browser = await chromium.launch({headless:true, ...(process.env.MEDIAARCHIVER_BROWSER ? {executablePath:process.env.MEDIAARCHIVER_BROWSER} : {})})
const page = await browser.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.goto(address + '/index.html')
await page.waitForLoadState('networkidle')
await page.getByRole('button', {name:'一键重建', exact:true}).click()
await page.getByText('正在同步', {exact:true}).waitFor()
await page.waitForLoadState('networkidle')
for (let attempt=0; attempt<50; attempt++) {
  const response = await page.request.get(address + '/api/v1/plugin/MediaArchiver/status', {headers:{Authorization:'Bearer local-test'}})
  const current = (await response.json()).data
  if (current.state !== 'running') { assert.equal(current.state, 'completed', JSON.stringify(current)); break }
  await new Promise(resolve => setTimeout(resolve, 100))
}
await page.waitForLoadState('networkidle')
await page.getByRole('button', {name:'刷新进度', exact:true}).click()
await page.getByText(/完成：1 台 Emby/).first().waitFor()
assert(await page.locator('tr').filter({hasText:'Remux专区'}).innerText(), 'Native page renders member table')
await page.getByRole('button', {name:'测试连接', exact:true}).click()
await page.getByText(/连接成功/).first().waitFor()
await page.screenshot({path:'.work/virtual-native-desktop.png', fullPage:true})
await page.getByRole('button', {name:'配置', exact:true}).click()
await page.getByText('MoviePilot 已配置的 Emby', {exact:true}).first().waitFor()
await page.getByRole('button', {name:'自动维护', exact:true}).click()
const cron = page.getByLabel('标准五段 Cron', {exact:true})
await cron.fill('0 4,16 * * *')
const saveResponse = page.waitForResponse(response => response.url().endsWith('/plugin/MediaArchiver') && response.request().method() === 'PUT')
await page.getByRole('button', {name:'保存配置', exact:true}).click()
assert((await (await saveResponse).json()).success)
await page.getByRole('button', {name:'自动维护', exact:true}).click()
assert.equal(await cron.inputValue(), '0 4,16 * * *')
await page.getByRole('button', {name:'功能', exact:true}).click()
await page.getByText(/0 4,16/).waitFor()
await page.request.post(address + '/api/v1/qa/fail-page', {headers:{Authorization:'Bearer local-test'}})
await page.reload()
await page.getByText('插件数据加载失败：HTTP 503').waitFor()
await page.getByRole('button', {name:'重试', exact:true}).click()
await page.getByRole('button', {name:'一键重建', exact:true}).waitFor()
await page.setViewportSize({width:390, height:844})
await page.screenshot({path:'.work/virtual-native-mobile.png', fullPage:true})
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
await page.getByRole('button', {name:'配置', exact:true}).click()
await page.getByRole('button', {name:'平台与榜单', exact:true}).click()
await page.getByRole('button', {name:'Netflix', exact:true}).click()
await page.getByLabel(/电影精选/).first().waitFor()
assert(await page.getByRole('checkbox').count() > 0)
await page.screenshot({path:'.work/virtual-native-config-mobile.png', fullPage:true})
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
assert.deepEqual(errors, [])
await browser.close()
console.log('PASS: native function/config render, rebuild/refresh, connection, PUT save/reload, source groups, 503 retry, desktop/mobile, no JS errors')
